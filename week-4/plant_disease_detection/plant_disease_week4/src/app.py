def load_metrics():
    if not os.path.exists(METRICS_PATH):
        return None
    with open(METRICS_PATH, "r") as f:
        return json.load(f)


def list_figures():
    if not os.path.isdir(FIGURES_DIR):
        return []
    files = sorted(f for f in os.listdir(FIGURES_DIR) if f.lower().endswith((".png", ".jpg", ".jpeg")))
    return [(f, FIGURE_CAPTIONS.get(f, f)) for f in files]


def _render_index(**extra):
    metrics = load_metrics()
    figures = list_figures()
    report_exists = os.path.exists(REPORT_PATH)
    report_text = ""
    if report_exists:
        with open(REPORT_PATH, "r") as f:
            report_text = f.read()

    bundle = _load_inference_bundle()
    model_available = bundle is not None
    model_type = bundle["meta"]["model_type"] if bundle else None
    class_names = bundle["meta"]["class_names"] if bundle else []

    ctx = dict(
        metrics=metrics,
        figures=figures,
        report_exists=report_exists,
        report_text=report_text,
        model_available=model_available,
        model_type=model_type,
        class_names=class_names,
        scan_error=None,
        prediction=None,
        uploaded_image_url=None,
    )
    ctx.update(extra)
    return render_template_string(PAGE_TEMPLATE, **ctx)


@app.route("/")
def index():
    return _render_index()


@app.route("/scan", methods=["POST"])
def scan():
    file = request.files.get("image")
    if file is None or file.filename == "":
        return _render_index(scan_error="Please choose an image file to scan.")

    if not allowed_file(file.filename):
        return _render_index(
            scan_error="Unsupported file type. Please upload a JPG, PNG, BMP, or TIFF image."
        )

    safe_name = secure_filename(file.filename)
    unique_name = f"{uuid.uuid4().hex}_{safe_name}"
    saved_path = os.path.join(UPLOAD_DIR, unique_name)
    file.save(saved_path)

    try:
        predicted_class, confidence, top3 = run_prediction(saved_path)
        prediction = {
            "predicted_class": predicted_class,
            "confidence": confidence,
            "top3": top3,
        }
        return _render_index(
            prediction=prediction,
            uploaded_image_url=url_for("serve_upload", filename=unique_name),
        )
    except Exception as e:
        return _render_index(scan_error=f"Could not analyze this image: {e}")


@app.route("/uploads/<path:filename>")
def serve_upload(filename):
    return send_from_directory(UPLOAD_DIR, filename)


@app.route("/figures/<path:filename>")
def serve_figure(filename):
    if not os.path.isdir(FIGURES_DIR):
        abort(404)
    return send_from_directory(FIGURES_DIR, filename)


@app.route("/results/classification_report.txt")
def download_report():
    if not os.path.exists(REPORT_PATH):
        abort(404)
    return send_from_directory(RESULTS_DIR, "classification_report.txt", mimetype="text/plain")


