_MODEL_CACHE = {"loaded": False}


def _load_inference_bundle():
    """Load (and cache) whatever model main.py trained, plus its metadata.
    Returns a dict, or None if outputs/results/inference_meta.json doesn't
    exist yet (i.e. main.py hasn't been run)."""
    if _MODEL_CACHE["loaded"]:
        return _MODEL_CACHE.get("bundle")

    _MODEL_CACHE["loaded"] = True
    if not os.path.exists(INFERENCE_META_PATH):
        _MODEL_CACHE["bundle"] = None
        return None

    with open(INFERENCE_META_PATH, "r") as f:
        meta = json.load(f)

    bundle = {"meta": meta}
    try:
        if meta["model_type"] == "baseline":
            import joblib
            bundle["clf"] = joblib.load(os.path.join(RESULTS_DIR, meta["baseline_model_path"]))
            bundle["scaler"] = joblib.load(os.path.join(RESULTS_DIR, meta["baseline_scaler_path"]))
        elif meta["model_type"] == "cnn":
            import tensorflow as tf
            bundle["cnn_model"] = tf.keras.models.load_model(
                os.path.join(RESULTS_DIR, meta["cnn_model_path"])
            )
        else:
            bundle = None
    except Exception as e:
        print(f"[app] Failed to load trained model for inference: {e}")
        bundle = None

    _MODEL_CACHE["bundle"] = bundle
    return bundle


def allowed_file(filename: str) -> bool:
    return "." in filename and filename.rsplit(".", 1)[1].lower() in ALLOWED_EXTENSIONS


def run_prediction(image_path: str):
    """Run the uploaded image through the exact preprocessing pipeline used
    during training, then through whichever model main.py trained.
    Returns (predicted_class, confidence_pct, top3 list[(class, pct)]) or
    raises an Exception with a user-friendly message on failure."""
    bundle = _load_inference_bundle()
    if bundle is None:
        raise RuntimeError(
            "No trained model found. Run 'python src/main.py' first to train "
            "and save a model, then try scanning again."
        )

    meta = bundle["meta"]
    img_size = tuple(meta["img_size"])
    class_names = meta["class_names"]

    # Same preprocessing used for every training/val/test image.
    img = preprocess_image(image_path, size=img_size, apply_denoise=meta.get("apply_denoise", True))

    if meta["model_type"] == "baseline":
        feats = extract_features(img)
        feature_cols = meta["feature_columns"]
        x = np.array([[feats.get(c, 0.0) for c in feature_cols]], dtype=np.float32)
        x_scaled = bundle["scaler"].transform(x)
        clf = bundle["clf"]
        probs = clf.predict_proba(x_scaled)[0]
        classes = list(clf.classes_)
    else:  # cnn
        x = np.expand_dims(img.astype(np.float32), axis=0)
        probs = bundle["cnn_model"].predict(x, verbose=0)[0]
        classes = class_names

    order = np.argsort(probs)[::-1]
    top3 = [(str(classes[i]), float(probs[i]) * 100.0) for i in order[:3]]
    predicted_class, confidence = top3[0]
    return predicted_class, confidence, top3


